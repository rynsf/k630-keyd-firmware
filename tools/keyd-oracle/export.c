/*
 * keyd-export: compile a keyd config into engine/kd_config.h tables, using keyd v2.6.0's own
 * parser so the firmware sees exactly what the daemon sees.
 *
 * usage: export <config> > kd_config_gen.c
 *
 * Refuses (exit 1) on anything the firmware engine does not implement: chords, macros,
 * commands, composite layers, and unsupported actions.
 */
#include <stdio.h>
#include <string.h>
#include "keyd.h"
#include "quiet_parse.h"

static int fail(const char *what)
{
	fprintf(stderr, "keyd-export: unsupported by the firmware engine: %s\n", what);
	return 1;
}

static int supported_op(int op)
{
	switch (op) {
	case OP_KEYSEQUENCE: case OP_ONESHOT: case OP_LAYER: case OP_LAYOUT: case OP_CLEAR:
	case OP_OVERLOAD: case OP_OVERLOAD_TIMEOUT: case OP_OVERLOAD_TIMEOUT_TAP: case OP_TOGGLE:
		return 1;
	}
	return 0;
}

static int check_desc(const struct config *c, const struct descriptor *d, int depth)
{
	if (!supported_op(d->op))
		return 0;
	if (d->op == OP_OVERLOAD || d->op == OP_OVERLOAD_TIMEOUT || d->op == OP_OVERLOAD_TIMEOUT_TAP) {
		if (depth > 0 || (size_t)d->args[1].idx >= c->nr_descriptors)
			return 0;
		const struct descriptor *a = &c->descriptors[d->args[1].idx];
		if (a->op != OP_KEYSEQUENCE && !check_desc(c, a, depth + 1))
			return 0;
	}
	return 1;
}

static void emit_desc(const struct descriptor *d)
{
	unsigned a0 = 0, a1 = 0, a2 = 0;
	switch (d->op) {
	case OP_KEYSEQUENCE: a0 = d->args[0].code; a1 = d->args[1].mods; break;
	case OP_OVERLOAD: a0 = d->args[0].idx; a1 = d->args[1].idx; break;
	case OP_OVERLOAD_TIMEOUT: case OP_OVERLOAD_TIMEOUT_TAP:
		a0 = d->args[0].idx; a1 = d->args[1].idx; a2 = d->args[2].timeout; break;
	case OP_CLEAR: break;
	default: a0 = d->args[0].idx; break;
	}
	printf("{%d, %u, %u, %u}", d->op, a0, a1, a2);
}

int main(int argc, char **argv)
{
	static struct config c;
	if (argc != 2) {
		fprintf(stderr, "usage: export <config>\n");
		return 2;
	}
	if (config_parse_quiet(&c, argv[1]) < 0) {
		fprintf(stderr, "keyd-export: failed to parse %s\n", argv[1]);
		return 2;
	}
	if (c.nr_macros) return fail("macros");
	if (c.nr_commands) return fail("commands");
	if (c.nr_layers > 32) return fail("more than 32 layers");

	int default_layout = 0;
	for (size_t i = 0; i < c.nr_layers; i++) {
		const struct layer *l = &c.layers[i];
		if (l->nr_chords) return fail("chords");
		if (l->type == LT_COMPOSITE) return fail("composite layers");
		for (int k = 0; k < 256; k++)
			if (l->keymap[k].op && !check_desc(&c, &l->keymap[k], 0)) {
				fprintf(stderr, "keyd-export: layer %s key %s: op %d\n", l->name,
					keycode_table[k].name, l->keymap[k].op);
				return fail("action");
			}
		if (c.default_layout[0] && l->type == LT_LAYOUT && !strcmp(l->name, c.default_layout))
			default_layout = (int)i;
	}
	for (size_t i = 0; i < c.nr_descriptors; i++)
		if (c.descriptors[i].op && !check_desc(&c, &c.descriptors[i], 1))
			return fail("auxiliary descriptor");

	printf("/* GENERATED by tools/keyd-oracle/export.c from %s (keyd v2.6.0 parser). Do not edit. */\n",
	       argv[1]);
	printf("#include \"kd_config.h\"\n\n");

	printf("const KD_CODE struct kd_desc kd_descs[] = {\n");
	for (size_t i = 0; i < c.nr_descriptors; i++) {
		printf("\t");
		emit_desc(&c.descriptors[i]);
		printf(", /* %zu */\n", i);
	}
	if (!c.nr_descriptors)
		printf("\t{0, 0, 0, 0},\n");
	printf("};\n\n");

	printf("const KD_CODE struct kd_bind kd_binds[] = {\n");
	unsigned first[32], count[32], n = 0;
	for (size_t i = 0; i < c.nr_layers; i++) {
		first[i] = n;
		count[i] = 0;
		for (int k = 0; k < 256; k++) {
			if (!c.layers[i].keymap[k].op)
				continue;
			printf("\t{%3d, ", k);
			emit_desc(&c.layers[i].keymap[k]);
			printf("}, /* %s: %s */\n", c.layers[i].name, keycode_table[k].name);
			count[i]++;
			n++;
		}
	}
	if (!n)
		printf("\t{0, {0, 0, 0, 0}},\n");
	printf("};\n\n");

	printf("const KD_CODE struct kd_layer kd_layers[] = {\n");
	for (size_t i = 0; i < c.nr_layers; i++)
		printf("\t{%d, 0x%02x, %u, %u}, /* %zu %s */\n",
		       c.layers[i].type == LT_LAYOUT ? 1 : 0, c.layers[i].mods, first[i], count[i], i,
		       c.layers[i].name);
	printf("};\n\n");

	printf("const KD_CODE struct kd_config kd_cfg = {%zu, %d, %ld, %ld, %d};\n", c.nr_layers,
	       default_layout, c.oneshot_timeout, c.overload_tap_timeout, c.disable_modifier_guard);
	return 0;
}
