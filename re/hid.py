# HID keyboard usage names (subset used for annotation)
N = {0x00: "", 0x01: "ErrRoll", 0x28: "Enter", 0x29: "Esc", 0x2A: "Bksp", 0x2B: "Tab", 0x2C: "Space", 0x2D: "-", 0x2E: "=",
     0x2F: "[", 0x30: "]", 0x31: "\\", 0x32: "#iso", 0x33: ";", 0x34: "'", 0x35: "`", 0x36: ",", 0x37: ".", 0x38: "/",
     0x39: "Caps", 0x46: "PrtSc", 0x47: "ScrLk", 0x48: "Pause", 0x49: "Ins", 0x4A: "Home", 0x4B: "PgUp", 0x4C: "Del",
     0x4D: "End", 0x4E: "PgDn", 0x4F: "Right", 0x50: "Left", 0x51: "Down", 0x52: "Up", 0x53: "NumLk", 0x64: "\\iso",
     0x65: "App", 0xE0: "LCtrl", 0xE1: "LShift", 0xE2: "LAlt", 0xE3: "LGui", 0xE4: "RCtrl", 0xE5: "RShift", 0xE6: "RAlt",
     0xE7: "RGui"}
for i in range(26): N[0x04 + i] = chr(ord("A") + i)
for i in range(9): N[0x1E + i] = str(i + 1)
N[0x27] = "0"
for i in range(12): N[0x3A + i] = f"F{i+1}"
for i in range(0x54, 0x64): N.setdefault(i, f"KP{i:02X}")


def name(c):
    return N.get(c, f"?{c:02X}")
